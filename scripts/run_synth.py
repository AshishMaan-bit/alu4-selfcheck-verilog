#!/usr/bin/env python3
"""
run_synth.py - Yosys logic synthesis of every design variant.

Variants (9 x 3 x 2 = 54 netlists):
  design             : base        = alu4_base_core (datapath only, err tied to 0)
                       dmr         = alu4_dmr_core (duplication + comparator)
                       sc_res3dup  = alu4_sc_core, residue-3 + logic duplication
                       sc_res3par  = alu4_sc_core, residue-3 + logic parity
                       sc_invdup   = alu4_sc_core, inverse-op + logic duplication
                       sc_invpar   = alu4_sc_core, inverse-op + logic parity
                       base_bs, sc_res3par_bs, sc_invpar_bs = the same with
                                     the bit-sliced, sharing-free datapath
  adder architecture : rca, cla, ks
  flow               : struct = 'synth -noabc'  -> generic gates that keep the
                                RTL structure (used to study architecture)
                       opt    = 'synth' with ABC -> technology-independent
                                optimised gate netlist

In every design the datapath(s) and the checker are
synthesised as separate hierarchies (keep_hierarchy) so the optimiser cannot
share logic between the function and its checker (or merge the two DMR
copies); the netlist is flattened only after technology mapping.

Outputs per variant in synth/out/<design>_<arch>_<flow>/ :
  synth.ys, yosys.log, netlist.v (gate-level Verilog), netlist.json, stat.txt
Summary : synth/synthesis_summary.csv
"""
import csv, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from gatesim import Netlist  # noqa: E402

ARCHS = {"rca": 0, "cla": 1, "ks": 2}
GATES = "AND,NAND,OR,NOR,XOR,XNOR,ANDNOT,ORNOT,MUX"
RTL = ["rtl/adder4.v", "rtl/alu4_datapath.v", "rtl/alu4_checker.v",
       "rtl/alu4_datapath_bs.v", "rtl/alu4_sc_core.v", "rtl/alu4_dmr_core.v",
       "rtl/alu4_base_core.v"]
DESIGNS = {  # name: (top module, DP_STYLE, ARITH_CHK, LOGIC_CHK)
    "base":          ("alu4_base_core", 0, None, None),
    "base_bs":       ("alu4_base_core", 1, None, None),
    "dmr":           ("alu4_dmr_core",  None, None, None),
    "sc_res3dup":    ("alu4_sc_core",   0, 0, 0),
    "sc_res3par":    ("alu4_sc_core",   0, 0, 1),
    "sc_invdup":     ("alu4_sc_core",   0, 1, 0),
    "sc_invpar":     ("alu4_sc_core",   0, 1, 1),
    "sc_res3par_bs": ("alu4_sc_core",   1, 0, 1),
    "sc_invpar_bs":  ("alu4_sc_core",   1, 1, 1),
}


def script(design, arch, flow, outdir):
    top, dps, achk, lchk = DESIGNS[design]
    s = [f"# auto-generated by scripts/run_synth.py : {design} {arch} {flow}",
         "read_verilog -Irtl " + " ".join(RTL),
         f"chparam -set ADDER_ARCH {ARCHS[arch]} {top}"]
    if dps is not None:
        s.append(f"chparam -set DP_STYLE {dps} {top}")
    if achk is not None:
        s.append(f"chparam -set ARITH_CHK {achk} -set LOGIC_CHK {lchk} {top}")
    s.append(f"hierarchy -check -top {top}")
    # datapath(s) and checker never share logic; in the bit-sliced datapath
    # every slice is also kept separate (no logic sharing between bits)
    s.append("setattr -mod -set keep_hierarchy 1 *alu4_datapath* *alu4_checker* "
             "*alu4_rslice* *alu4_cslice* *alu4_vslice*")
    s.append("synth -flatten -top %s%s" % (top, " -noabc" if flow == "struct" else ""))
    if flow == "opt":
        # two extra ABC passes: the first default pass leaves noticeable slack
        s += [f"abc -g {GATES}", "opt_clean"] * 2
    s += ["setattr -mod -unset keep_hierarchy",
          "flatten",
          "opt_clean -purge",
          f"tee -o {outdir}/stat.txt stat",
          f"tee -a {outdir}/stat.txt ltp -noff",
          f"write_verilog -noattr {outdir}/netlist.v",
          f"write_json {outdir}/netlist.json"]
    return "\n".join(x for x in s if x) + "\n"


def main():
    rows = []
    for design in DESIGNS:
        for arch in ARCHS:
            for flow in ("struct", "opt"):
                name = f"{design}_{arch}_{flow}"
                outdir = os.path.join("synth", "out", name)
                os.makedirs(os.path.join(ROOT, outdir), exist_ok=True)
                ys = os.path.join(outdir, "synth.ys")
                with open(os.path.join(ROOT, ys), "w") as f:
                    f.write(script(design, arch, flow, outdir))
                r = subprocess.run(["yosys", "-q", "-l", os.path.join(outdir, "yosys.log"), "-s", ys],
                                   cwd=ROOT, capture_output=True, text=True)
                if r.returncode:
                    print(r.stdout, r.stderr); sys.exit(f"yosys failed for {name}")
                nl = Netlist(os.path.join(ROOT, outdir, "netlist.json"))
                st = nl.stats()
                row = {"variant": name, "design": design, "adder": arch, "flow": flow, **st}
                rows.append(row)
                print(f"{name:16s} cells={st['cells']:4d} trans_est={st['transistors']:5d} "
                      f"depth={st['depth']:2d}  {st['by_type']}")
    keys = ["variant", "design", "adder", "flow", "cells", "transistors", "depth", "by_type"]
    with open(os.path.join(ROOT, "synth", "synthesis_summary.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in rows:
            r = dict(r); r["by_type"] = json.dumps(r["by_type"])
            w.writerow({k: r[k] for k in keys})


if __name__ == "__main__":
    main()
